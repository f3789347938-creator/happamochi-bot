-- 連呼対策(A案): ユーザーごとに5秒のクールダウンを設ける。
--
-- C案(直前と同じ本文なら加算しない)は、「あ+改行+ランダムな数字」のように
-- 毎回本文を変える手口に対して無力だった(実測: 16通送って16通すべて加算)。
-- 本文を一切見ず、時間だけで判定することで回避できないようにする。
--
-- 粒度は「ユーザーごと」。EXP自体がユーザー単位の累計値であり、
-- グループごとにすると複数グループを渡り歩いて無制限に稼げてしまうため。
--
-- 既存の exp_last_message(C案用)に列を足す形にすると、意味の違う2つの
-- 判定が1テーブルに混ざって分かりにくいため、時刻だけを持つ列を追加する。
-- 方針どおり「追加のみ」。既存テーブルの構造・データには触れない。
ALTER TABLE exp_last_message ADD COLUMN last_exp_at DATETIME;

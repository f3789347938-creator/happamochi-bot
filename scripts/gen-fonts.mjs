// フォント番号 1〜12 の対応。
// 手元(Linux)に確実に存在する Noto CJK JP のウェイト/系統から、
// 「見た目がはっきり違う」ものを選んで12種にする。
// ※ 商用の丸ゴシック等は同梱できないため、Notoの範囲で最大限差を出す。
const FONTS = [
  { n: 1, file: 'NotoSansCJK-Regular.ttc', idx: 0, label: 'ゴシック' },
  { n: 2, file: 'NotoSansCJK-Bold.ttc', idx: 0, label: 'ゴシック太' },
  { n: 3, file: 'NotoSansCJK-Light.ttc', idx: 0, label: 'ゴシック細' },
  { n: 4, file: 'NotoSansCJK-Medium.ttc', idx: 0, label: 'ゴシック中' },
  { n: 5, file: 'NotoSansCJK-Black.ttc', idx: 0, label: 'ゴシック極太' },
  { n: 6, file: 'NotoSansCJK-Thin.ttc', idx: 0, label: 'ゴシック極細' },
  { n: 7, file: 'NotoSerifCJK-Regular.ttc', idx: 0, label: '明朝' },
  { n: 8, file: 'NotoSerifCJK-Bold.ttc', idx: 0, label: '明朝太' },
  { n: 9, file: 'NotoSerifCJK-Light.ttc', idx: 0, label: '明朝細' },
  { n: 10, file: 'NotoSerifCJK-Black.ttc', idx: 0, label: '明朝極太' },
  { n: 11, file: 'NotoSerifCJK-Medium.ttc', idx: 0, label: '明朝中' },
  { n: 12, file: 'NotoSansCJK-Regular.ttc', idx: 5, label: '等幅' },
]

const SRC_DIRS = [
  '/usr/share/fonts/opentype/noto',
  '/usr/share/fonts/truetype/noto',
]

function findSrc(name) {
  for (const d of SRC_DIRS) {
    const p = path.join(d, name)
    if (fs.existsSync(p)) return p
  }
  return null
}

fs.mkdirSync(OUT, { recursive: true })
const textFile = path.join(OUT, '.chars.txt')
fs.writeFileSync(textFile, JOYO, 'utf8')

const manifest = []
let total = 0
for (const f of FONTS) {
  const src = findSrc(f.file)
  if (!src) {
    console.log(`  ⚠️  ${f.file} が見つかりません (フォント${f.n} をスキップ)`)
    continue
  }
  const out = path.join(OUT, `f${f.n}.ttf`)
  execFileSync('pyftsubset', [
    src,
    `--unicodes=${UNICODES}`,
    `--text-file=${textFile}`,
    `--output-file=${out}`,
    `--font-number=${f.idx}`,
    '--no-hinting',
    '--desubroutinize',
    '--drop-tables+=DSIG',
    '--name-IDs=*',
    '--recalc-bounds',
  ])
  const size = fs.statSync(out).size
  total += size
  manifest.push({ n: f.n, label: f.label, bytes: size })
  console.log(`  ✅ フォント${String(f.n).padStart(2)} ${f.label.padEnd(8, '　')} ${(size / 1024).toFixed(0)} KB  → public/static/fonts/quote/f${f.n}.ttf`)
}

fs.unlinkSync(textFile)
fs.writeFileSync(
  path.join(OUT, 'manifest.json'),
  JSON.stringify({ fonts: manifest, totalBytes: total }, null, 2)
)
console.log(`\n  合計 ${(total / 1024 / 1024).toFixed(2)} MB (${manifest.length}種)`)
console.log(`  収録文字: 常用漢字${JOYO.length}字 + かな + 記号\n`)

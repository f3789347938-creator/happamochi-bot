// 名言カードの「フォント番号 1〜12」用フォントを生成する。
//
// なぜサブセットするのか:
//   日本語フォントは1本 5MB 級で、Cloudflare Workers のバンドル上限
//   (圧縮後 10MB) に対して 12 本を丸ごと積むのは不可能。
//   CJK統合漢字を全部入れると 1本 10MB になる(実測)。
//   一方、日本語の実用文で必要な「かな + 記号 + 常用漢字 + 人名用漢字の主要」
//   に絞ると 1本 約400KB(gzip 300KB) まで落ちる(実測)。
//   12本で raw 約5MB / gzip 約3.6MB。既存の本文フォント2本とは別系統で
//   持つため、フォントはWorkerに埋め込まず public/static/fonts/quote/ に
//   置き、生成時に必要な1本だけHTTPで取得する方式にする(後述)。
//
// なぜWorkerに埋め込まないのか:
//   既存の NotoSansJP-Bold/Regular は inject-wasm.mjs で Worker に静的
//   埋め込みしており、この2本だけで raw 10.6MB / gzip 6.1MB を占めている。
//   ここに12本追加すると確実に上限を超える。名言カードのフォント指定は
//   任意パラメータなので、指定されたときだけ同一オリジンから fetch する。
//   同一オリジンの静的アセットなので追加コストはほぼ無い。
//
// 使い方:
//   node scripts/gen-fonts.mjs

// ─── LINE Webhook ───
app.post('/webhook', async (c) => {
  const bodyText = await c.req.text()
  const signature = c.req.header('x-line-signature') ?? null

  const valid = await verifySignature(c.env.LINE_CHANNEL_SECRET, bodyText, signature)

  await c.env.DB.prepare(
    `INSERT INTO webhook_debug_logs (timestamp, request_body, has_signature, event_type) VALUES (?, ?, ?, ?)`
  )
    .bind(new Date().toISOString(), bodyText.slice(0, 2000), signature ? 1 : 0, valid ? 'valid' : 'invalid_signature')
    .run()

  if (!valid) return c.json({ error: 'invalid signature' }, 401)

  const payload = JSON.parse(bodyText) as { events: any[] }
  const events = payload.events ?? []

  // IMPORTANT: LINE's webhook connection has a short timeout. We must ACK
  // (return 200) immediately after verifying the signature — NOT after
  // finishing all the DB writes / profile fetches / Reply API calls.
  // Otherwise LINE cancels the connection before we ever call Reply API,
  // which is exactly why real LINE traffic showed up as
  // `outcome: "canceled"` (cpuTime≈4ms, wallTime≈2000ms) in the tail logs
  // while our own sandbox curl requests (which just wait patiently) always
  // succeeded. So: respond first, then keep processing in the background
  // via waitUntil so the replyToken is still fresh when we use it.
  const baseUrl = new URL(c.req.url).origin

  const work = (async () => {
    for (const event of events) {
      try {
        await handleEvent(c.env, event, baseUrl)
      } catch (e: any) {
        await c.env.DB.prepare(
          `INSERT INTO webhook_debug_logs (timestamp, request_body, has_signature, event_type, error_message) VALUES (?, ?, ?, ?, ?)`
        )
          .bind(new Date().toISOString(), JSON.stringify(event).slice(0, 2000), 1, event.type, String(e?.message ?? e))
          .run()
      }
    }
  })()

  // 自動テスト専用の同期モード。waitUntil は応答後に走るため、テスト側から
  // 「処理が終わったか」を知る手段が無く、固定の待ち時間に頼ると不安定になる。
  // テスト用のID(下の接頭辞)のイベントだけに限定し、処理完了まで待ってから
  // 200を返す。実LINEのトラフィックは必ずこれらの接頭辞にならないため、
  // 本番の挙動は一切変わらない。
  // 個人トーク(source.type === 'user')のテストもあるため、
  // グループIDだけでなくユーザーIDの接頭辞も見る。
  const TEST_ID_PREFIXES = ['Cchess_test_', 'Cpf_test_', 'Upf_test_']
  const isTestEvent = (e: any) => {
    const gid = String(e?.source?.groupId ?? '')
    const uid = String(e?.source?.userId ?? '')
    return TEST_ID_PREFIXES.some((p) => gid.startsWith(p) || uid.startsWith(p))
  }
  const allTestEvents = events.length > 0 && events.every(isTestEvent)
  if (allTestEvents) {
    await work
    return c.json({ ok: true, sync: true })
  }

  c.executionCtx.waitUntil(work)

  return c.json({ ok: true })
})

async function handleEvent(env: Bindings, event: any, baseUrl: string) {
  switch (event.type) {
    case 'unsend':
      await handleUnsend(env, event)
      return

    case 'message':
      await handleMessageEvent(env, event, baseUrl)
      return

    case 'postback':
      await handlePostback(env, event, baseUrl)
      return

    case 'memberJoined':
      await handleMemberJoined(env, event)
      return

    case 'join':
      if (event.source.type === 'group') {
        const groupId = event.source.groupId
        const summary = await getGroupSummary(env, groupId)
        await ensureGroupMetadata(env, groupId, summary?.groupName ?? null)
      }
      return

    case 'leave':
      // Previously unhandled (fell through to default/no-op): group_metadata
      // never recorded that the bot was removed from a group, so old rows
      // looked identical to currently-joined groups. Record left_at so we
      // can tell "currently joined" apart from "invited once, since removed".
      if (event.source.type === 'group') {
        await markGroupLeft(env, event.source.groupId)
        // チェスの進行中対局は中断として保存(勝敗はつけない)
        try {
          await onBotLeftGroup(env, event.source.groupId)
        } catch {
          /* チェスの中断処理失敗は既存処理に影響させない */
        }
      }
      return

    default:
      return
  }
}

async function handleMemberJoined(env: Bindings, event: any) {
  const groupId = event.source.groupId
  if (!groupId) return

  const joined = event.joined?.members ?? []

  // Webhook再送対策: 同じ memberJoined イベントを2回処理しない。
  // LINEは応答が遅い・失敗したと判断すると同じイベントを再送するため、
  // 重複排除が無いと歓迎メッセージが2通続けて出てしまう(実際に発生した)。
  //
  // webhookEventId が無いイベントでも取りこぼさないよう、
  // 「グループ + 参加した人 + 分単位の時刻」でも一度だけに絞る。
  // (markEventProcessed は ID が null のとき素通りさせる作りのため)
  const idKey = event.webhookEventId
    ? `mj_${event.webhookEventId}`
    : `mj_${groupId}_${joined.map((m: any) => m?.userId ?? '?').sort().join('_')}_${Math.floor(
        (event.timestamp ?? Date.now()) / 60000
      )}`
  const fresh = await markEventProcessed(env, idKey)
  if (!fresh) return
  const resolved = await Promise.all(
    joined.map(async (m: any) => {
      const p = await getProfile(env, m.userId, groupId)
      return { userId: m.userId, displayName: p?.displayName }
    })
  )
  const messages = await buildWelcomeMessages(env, groupId, resolved)
  if (messages && event.replyToken) {
    await flushQueueOnReply(env, groupId, event.replyToken, messages)
  }
}

async function handleMessageEvent(env: Bindings, event: any, baseUrl: string) {
  const source = event.source
  const isGroup = source.type === 'group'
  const groupId = source.groupId
  const userId = source.userId
  const replyToken: string | undefined = event.replyToken
  const message = event.message

  let displayName: string | null = null
  let pictureUrl: string | null = null
  if (userId) {
    const profile = await getProfile(env, userId, isGroup ? groupId : undefined)
    displayName = profile?.displayName ?? null
    pictureUrl = profile?.pictureUrl ?? null
  }

  // 個人ステータスのEXP/ポイント加算(追加機能)。
  //   ・本人が新しく送った1通につき EXP+1・ポイント+1。
  //   ・種類(文章/画像/スタンプ/コマンド)で除外しない。
  //   ・グループと個人トークの両方が対象。
  //   ・獲得制限は付けない。ただし「1通を1回と数える」ため、
  //     webhookEventId(無ければ message.id)で二重加算だけ防ぐ。
  //   ・Bot自身の返信やボタン操作(Postback)はここを通らないので加算されない。
  // 失敗しても既存処理を止めないよう try/catch で完全に隔離する。
  if (userId) {
    try {
      const eventKey = event.webhookEventId ?? (message?.id ? `msg_${message.id}` : null)
      await addExpForMessage(env, userId, eventKey, displayName, pictureUrl)
    } catch {
      /* EXP加算の失敗は既存機能に影響させない */
    }
  }

  if (isGroup) {
    // Only call the LINE Group Summary API when we don't have a name yet
    // for this group — avoids hitting that endpoint on every single
    // message once group_name is populated.
    const existingMeta = await env.DB.prepare(`SELECT group_name FROM group_metadata WHERE group_id = ?`)
      .bind(groupId)
      .first<{ group_name: string | null }>()
    let groupName = existingMeta?.group_name ?? null
    if (!groupName) {
      const summary = await getGroupSummary(env, groupId)
      groupName = summary?.groupName ?? null
    }
    await ensureGroupMetadata(env, groupId, groupName)
    await touchGroupMember(env, groupId, userId, displayName)

    // ランキングの「主な活動時間帯」用の時間帯別集計(追加機能)。
    // 既存の touchGroupMember には一切手を入れず、新テーブルにだけ積む。
    // recordHourlyActivity は内部で例外を飲むが、万一に備えてここでも
    // 囲い、この集計の失敗が Bot 本体の処理を止めないようにする。
    try {
      await recordHourlyActivity(env, groupId)
    } catch {
      /* ranking の集計失敗は既存機能に影響させない */
    }

    if (message.type === 'text') {
      await cacheGroupMessage(env, groupId, message.id, userId, displayName, pictureUrl, message.text)
    }

    // Lazily check push-free scheduled-ish features (no cron available).
    await checkAndQueueBirthdays(env, groupId)
    // 運勢の自動配信は廃止した(機能ごと削除)。
    await checkAndQueueWeeklyRanking(env, groupId)
    // 未送信のお知らせをグループごとに1回だけ配信する。
    // キューに積むだけなので Push API は使わず、実送信はこの発言への
    // Reply に便乗する。失敗しても他の機能を巫がないよう try/catch で囲う。
    try {
      await checkAndQueueAnnouncements(env, groupId)
    } catch {
      /* お知らせ配信の失敗は既存機能に影響させない */
    }
    // Any message (not just othello commands or board taps) can be the
    // trigger that notices an abandoned in-progress game and announces its
    // timeout — there's no cron/push to do this proactively.
    await checkAndQueueOthelloTimeout(env, groupId)
  }

  if (message.type !== 'text' || !replyToken) {
    // Still flush any queued broadcasts if we at least have a replyToken.
    if (replyToken && isGroup) await flushQueueOnReply(env, groupId, replyToken, [])
    return
  }

  const text: string = message.text.trim()
  const directReplies = await routeCommand(env, {
    text,
    isGroup,
    groupId,
    userId,
    displayName,
    pictureUrl,
    baseUrl,
    quotedMessageId: message.quotedMessageId,
  })

  if (isGroup) {
    await flushQueueOnReply(env, groupId, replyToken, directReplies)
  } else if (directReplies.length > 0) {
    await replyMessage(env, replyToken, directReplies, userId)
  }
}

// Handles taps on the Othello board (a `postback` action on a legal-move
// cell). Reply-only: the postback event carries its own one-time
// replyToken, exactly like a message event, so this never needs Push API.
async function handlePostback(env: Bindings, event: any, baseUrl: string) {
  const source = event.source
  const userId = source.userId
  const replyToken: string | undefined = event.replyToken
  const data: string = event.postback?.data ?? ''

  // --- 個人ステータス・着せ替え・共通称号(追加機能) ---
  // グループでも個人トークでも動かす必要があるため、
  // 既存のグループ限定チェックより前に処理する。
  //
  // 操作主体は必ず source.userId。PostbackのデータにユーザーIDは
  // 入っていないので、他人のカードのボタンを押しても、そのカードの
  // 持ち主のポイント・装備は一切変わらず、押した本人の画面が出る。
  if (data.startsWith('pf|') && userId && replyToken) {
    // Webhook再送・連打対策: 同じ webhookEventId は1回だけ処理する。
    // (購入の二重成立は point_ledger の一意制約でも防いでいる)
    const fresh = await markEventProcessed(env, event.webhookEventId ?? null)
    if (!fresh) return
    try {
      const msgs = await handleProfilePostback(
        env,
        {
          userId,
          displayName: null,
          pictureUrl: null,
          baseUrl,
        },
        data
      )
      if (msgs && msgs.length > 0) {
        if (source.type === 'group' && source.groupId) {
          await flushQueueOnReply(env, source.groupId, replyToken, msgs.slice(0, 5))
        } else {
          await replyMessage(env, replyToken, msgs.slice(0, 5))
        }
      }
    } catch {
      await replyMessage(env, replyToken, [
        { type: 'text', text: 'この操作でエラーが発生しました。「ステータス」で開き直せます。' },
      ])
    }
    return
  }

  // --- ヘルプメニュー(横スワイプのカルーセルと案内画面) ---
  // グループでも個人トークでも動くよう、グループ限定チェックより前に置く。
  //
  // 操作主体は必ず source.userId。トークンにユーザーIDは入っていない。
  // 「メニューを開く」だけの操作では状態を変えない。設定変更は確認をはさみ、
  // 確認意図はサーバー(menu_confirmations)に保存して本人・グループ・期限を
  // 照合してから、既存コマンドの処理をそのまま呼ぶ。
  if (data.startsWith('hm|') && userId && replyToken) {
    // Webhook再送・連打対策: 同じ webhookEventId は1回だけ処理する。
    const fresh = await markEventProcessed(env, event.webhookEventId ?? null)
    if (!fresh) return
    const isGroup = source.type === 'group'
    const gid: string | undefined = isGroup ? source.groupId : undefined
    try {
      const profile = await getProfile(env, userId, gid)
      const result = await handleMenuPostback(
        env,
        {
          isGroup,
          groupId: gid,
          userId,
          displayName: profile?.displayName ?? null,
          siteUrl: SITE_URL,
        },
        data
      )
      let msgs = result?.messages ?? []
      // 表示だけの既存コマンドは、既存の routeCommand をそのまま通す。
      // これにより既存のカード・文言・内部処理を作り直さずに再利用する。
      if (result?.runExisting) {
        msgs = await routeCommand(env, {
          text: result.runExisting,
          isGroup,
          groupId: gid,
          userId,
          displayName: profile?.displayName ?? null,
          pictureUrl: profile?.pictureUrl ?? null,
          baseUrl,
        })
      }
      if (msgs.length > 0) {
        if (isGroup && gid) {
          await flushQueueOnReply(env, gid, replyToken, msgs.slice(0, 5))
        } else {
          await replyMessage(env, replyToken, msgs.slice(0, 5))
        }
      }
    } catch {
      await replyMessage(env, replyToken, [
        { type: 'text', text: 'この操作でエラーが発生しました。「ヘルプ」で開き直せます。' },
      ])
    }
    return
  }

  // 以下はグループ限定の既存処理(チェス・オセロ)。
  if (source.type !== 'group') return
  const groupId = source.groupId
  if (!groupId || !userId || !replyToken) return

  // --- チェス ---
  // data が c で始まるチェス用トークンのときだけ処理する。
  // 本人確認は Postback の中身ではなく source.userId で行う(handleChessPostback内)。
  if (/^c[a-z]{1,2}\|/.test(data)) {
    // Webhook再送・二重タップ対策: 同じ webhookEventId は1回だけ処理する
    const fresh = await markEventProcessed(env, event.webhookEventId ?? null)
    if (!fresh) return
    try {
      const msgs = await handleChessPostback(
        env,
        { groupId, userId, baseUrl },
        data
      )
      if (msgs && msgs.length > 0) {
        await flushQueueOnReply(env, groupId, replyToken, msgs.slice(0, 1))
      }
    } catch (e: any) {
      await flushQueueOnReply(env, groupId, replyToken, [
        { type: 'text', text: 'チェスの処理でエラーが発生しました。「盤面」で最新の状態を確認できます。' },
      ])
    }
    return
  }

  const othelloMatch = data.match(/^othello:(\d+),(\d+)$/)
  if (othelloMatch) {
    const row = Number(othelloMatch[1])
    const col = Number(othelloMatch[2])
    const profile = await getProfile(env, userId, groupId)
    const result = await applyOthelloMove(env, groupId, userId, row, col, profile?.displayName ?? null)
    // "silent" rejections (same user re-tapping within 5s of their last
    // rejected tap, e.g. "相手の番です。" spam) intentionally send NOTHING —
    // not even to flush the broadcast queue, since a tap isn't a real
    // message and shouldn't be the trigger for unrelated queued notices.
    if (!result.ok && result.silent) return
    const message = result.ok
      ? buildOthelloMessage(result.game, result.note)
      : { type: 'text', text: result.reason }
    await flushQueueOnReply(env, groupId, replyToken, [message])
  }
}

// Combine (a) any direct reply this command produced with (b) whatever is
// sitting in the push-free broadcast queue for this group, then send it all
// in ONE free Reply call (LINE allows up to 5 messages per reply).
//
// IMPORTANT: queued broadcasts are only marked delivered AFTER we confirm
// the reply call actually succeeded. If the reply fails (expired/invalid
// replyToken, network error, etc.) the broadcast rows stay pending and will
// be retried on the next incoming message — nothing is silently lost.
async function flushQueueOnReply(env: Bindings, groupId: string, replyToken: string, direct: LineMessage[]) {
  const { messages: queued, ids: queuedIds } = await peekBroadcasts(env, groupId)
  const combined = [...direct, ...queued].slice(0, 5)
  if (combined.length === 0) return

  const result = await replyMessage(env, replyToken, combined, groupId)
  if (result.ok) {
    await markBroadcastsDelivered(env, queuedIds)
  }
  // If it failed, direct replies are lost (nothing we can do — the
  // replyToken is already spent/invalid either way), but queued broadcasts
  // remain pending and will be included in the next reply attempt.
}

interface CommandCtx {
  text: string
  isGroup: boolean
  groupId?: string
  userId?: string
  displayName: string | null
  pictureUrl: string | null
  baseUrl: string
  quotedMessageId?: string
}

async function routeCommand(env: Bindings, ctx: CommandCtx): Promise<LineMessage[]> {
  const { text } = ctx

  // 固定テストコマンド。今後は言葉を変えず、これだけで動作確認する。
  if (text === 'テスト') {
    return [{ type: 'text', text: `テスト成功 (${new Date().toISOString()})` }]
  }

  // `ヘルプ` は横スワイプのメニューカルーセルを出す。
  // 文字のコマンド一覧は、メニューの「ガイド → 全コマンド」から見られる。
  // 既存の別名 `help` もそのまま同じ扱い。新しい呼び名は追加していない。
  // メニューの組み立てに失敗しても、従来のテキストヘルプへ必ず落ちる。
  if (text === 'ヘルプ' || text.toLowerCase() === 'help') {
    try {
      const menu = handleMenuText(
        {
          isGroup: ctx.isGroup,
          groupId: ctx.groupId,
          userId: ctx.userId,
          displayName: ctx.displayName,
          siteUrl: SITE_URL,
        },
        text === 'ヘルプ' ? 'ヘルプ' : 'help'
      )
      if (menu && menu.length > 0) return menu
    } catch {
      /* メニューの不具合でヘルプ自体が止まらないよう、下のテキストへ落ちる */
    }
    return [{ type: 'text', text: HELP_TEXT }]
  }

  // --- 個人ステータス・着せ替え・共通称号(追加機能) ---
  // 「ステータス」「着せ替え」「共通称号一覧」「共通称号装備」
  // 「共通称号確認」「称号検索」だけに反応する。
  // 既存の「称号一覧」「称号装備」「称号確認」はグループ別称号のまま
  // 下の方で処理されるので、ここでは触らない。
  // グループでも個人トークでも使える(個人トークへ誘導しない)。
  // 失敗しても他のコマンドを止めないよう try/catch で囲う。
  if (ctx.userId) {
    try {
      const pfMsgs = await handleProfileText(
        env,
        {
          userId: ctx.userId,
          displayName: ctx.displayName,
          pictureUrl: ctx.pictureUrl,
          baseUrl: ctx.baseUrl,
        },
        text
      )
      if (pfMsgs) return pfMsgs
    } catch {
      /* 個人ステータス機能の失敗は既存コマンドに影響させない */
    }
  }

  // --- チェス(グループ対局) ---
  // 「チェス」「盤面」「チェス ヘルプ」だけに反応し、それ以外の会話には
  // 一切反応しない(handleChessText が null を返す)。
  // グループ以外(個別トーク)では導入方法を案内する。
  if (text === 'チェス' || text === '盤面' || text === 'チェス ヘルプ' || text === 'チェスヘルプ') {
    if (!ctx.isGroup || !ctx.groupId) {
      return [
        {
          type: 'text',
          text:
            'チェスはグループトークで対局する機能です。\n\n' +
            '使い方:\n' +
            '1. このBOTをグループに招待する\n' +
            '2. グループで「チェス」と送る\n' +
            '3. 別の人が「対局に参加」を押すと開始\n\n' +
            '※オープンチャットには対応していません。\n' +
            '※ルールは「チェス ヘルプ」で確認できます。',
        },
      ]
    }
    try {
      const chessMsgs = await handleChessText(
        env,
        { groupId: ctx.groupId, userId: ctx.userId ?? null, baseUrl: ctx.baseUrl },
        text
      )
      if (chessMsgs) return chessMsgs
    } catch {
      return [{ type: 'text', text: 'チェスの処理でエラーが発生しました。もう一度お試しください。' }]
    }
  }

  // グループ発言数ランキング。既存に同名コマンドは存在しない
  // (週間個人ランキングは自動配信で、コマンドは未実装だった)ので
  // 新規追加している。失敗しても他の応答を巫がないよう try/catch で囲う。
  if ((text === 'ランキング' || text === '順位') && ctx.isGroup && ctx.groupId) {
    try {
      const reply = await buildGroupRankingReply(env, ctx.groupId, SITE_URL)
      return [{ type: 'text', text: reply }]
    } catch {
      return [{ type: 'text', text: 'ランキングの取得に失敗しました。' }]
    }
  }

  if (text === 'お知らせ') {
    const messages = getLatestAnnouncementMessages(ctx.isGroup ? ctx.groupId ?? null : null)
    if (messages.length === 0) return [{ type: 'text', text: '現在お知らせはありません。' }]
    return messages
  }

  // 運勢機能(「運勢」「今日の運勢」「星座登録」「星座登録解除」)は削除した。
  // 毎日の自動配信がグループの会話に割り込んでうっとうしいという指摘を受け、
  // まず自動配信を止め、続いて機能そのものを廃止した。
  // ・src/features/fortune.ts は削除済み
  // ・DBのテーブル(user_zodiac_signs / daily_fortunes / daily_fortune_sent)は
  //   既存データを壊さない方針に従い残してある。特に daily_fortune_sent は
  //   誕生日機能が「birthday_<groupId>」というキーで流用しているため、
  //   消すと誕生日のお祝いが毎回重複送信されるようになる。絶対に消さない。

  const birthdayMatch = text.match(/^誕生日登録\s*(\d{1,2})\/(\d{1,2})$/)
  if (birthdayMatch && ctx.isGroup && ctx.groupId && ctx.userId) {
    const month = parseInt(birthdayMatch[1], 10)
    const day = parseInt(birthdayMatch[2], 10)
    if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      await registerBirthday(env, ctx.groupId, ctx.userId, ctx.displayName ?? '不明', month, day)
      return [{ type: 'text', text: `誕生日を${month}/${day}として登録しました` }]
    }
    return [{ type: 'text', text: '日付の形式が正しくありません。例: 誕生日登録 4/1' }]
  }

  if (text === '誕生日登録解除' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const removed = await unregisterBirthday(env, ctx.groupId, ctx.userId)
    return [{ type: 'text', text: removed ? '誕生日の登録を解除しました' : '誕生日は登録されていません' }]
  }

  if (text === '取り消し通知オフ' && ctx.isGroup && ctx.groupId) {
    await env.DB.prepare(
      `INSERT INTO unsend_restore_settings (group_id, enabled) VALUES (?, 0)
       ON CONFLICT(group_id) DO UPDATE SET enabled = 0, updated_at = CURRENT_TIMESTAMP`
    )
      .bind(ctx.groupId)
      .run()
    return [{ type: 'text', text: '取り消し通知をオフにしました' }]
  }

  if (text === '取り消し通知オン' && ctx.isGroup && ctx.groupId) {
    await env.DB.prepare(
      `INSERT INTO unsend_restore_settings (group_id, enabled) VALUES (?, 1)
       ON CONFLICT(group_id) DO UPDATE SET enabled = 1, updated_at = CURRENT_TIMESTAMP`
    )
      .bind(ctx.groupId)
      .run()
    return [{ type: 'text', text: '取り消し通知をオンにしました' }]
  }

  if (text === 'ウェルカムオフ' && ctx.isGroup && ctx.groupId) {
    await setWelcomeSetting(env, ctx.groupId, false)
    return [{ type: 'text', text: 'ウェルカムメッセージをオフにしました' }]
  }
  if (text === 'ウェルカムオン' && ctx.isGroup && ctx.groupId) {
    await setWelcomeSetting(env, ctx.groupId, true)
    return [{ type: 'text', text: 'ウェルカムメッセージをオンにしました' }]
  }
  const welcomeMsgMatch = text.match(/^ウェルカムメッセージ設定\s*(.+)$/s)
  if (welcomeMsgMatch && ctx.isGroup && ctx.groupId) {
    await setWelcomeSetting(env, ctx.groupId, true, welcomeMsgMatch[1].trim())
    return [{ type: 'text', text: 'ウェルカムメッセージを設定しました' }]
  }
  if (text === 'ウェルカムメッセージ解除' && ctx.isGroup && ctx.groupId) {
    await clearWelcomeMessage(env, ctx.groupId)
    return [{ type: 'text', text: 'カスタムウェルカムメッセージを解除しました(デフォルトの歓迎文に戻ります)' }]
  }

  // Reply mode: bare "めいく" (no colon/text) sent as a LINE reply to someone
  // else's message. quotedMessageId points at the ORIGINAL message, so the
  // card must use ITS author's name/icon and ITS text — not the replier's.
  // 装飾の一覧。返信モードの判定より先に置く必要がある
  // (「めいく 装飾」が返信モードのパラメータとして食われないようにする)。
  if (/^めいく[ 　]*(装飾|ヘルプ|help)$/i.test(text)) {
    const fontList = Object.entries(FONT_LABELS)
      .map(([n, l]) => `${n}:${l}`)
      .join(' / ')
    return [
      {
        type: 'text',
        text:
          '名言カードの装飾\n\n' +
          '【書き方】\n' +
          'めいく[装飾]:[テキスト]\n' +
          '返信のときは「めいく[装飾]」\n' +
          'スペースはあってもなくてもOK\n' +
          '装飾は続けて書けます（例: newbold虹7）\n\n' +
          '【見た目】\n' +
          'bold … 文字を太字\n' +
          'rev … アイコンを左右反転\n' +
          'mono … アイコンを白黒\n' +
          'whi … 白ベースで生成\n' +
          'new … 新レイアウト（右上に日付）\n\n' +
          '【色】\n' +
          '虹 … 1文字ずつ虹色\n' +
          '赤 橙 黄 緑 青 藍 紫 桃 水 白 黒 金 銀\n' +
          '春 夏 秋 冬 … 季節テーマ（1文字ずつ変化）\n' +
          '#FF00AA … 好きな色コード\n\n' +
          '【フォント 1〜12】\n' +
          fontList +
          '\n\n【例】\n' +
          'めいく虹:やったー\n' +
          'めいくbold虹:やったー\n' +
          'めいくnew7:静かな夜\n' +
          'めいくwhi#0088FF:おはよう\n' +
          'めいくrevmono （他人の発言に返信して）',
      },
    ]
  }

  // 返信モード: 「めいく」または「めいく<装飾>」を他人の発言への
  // 返信として送る。装飾部分(bold, mono, 虹, 3 など)は任意で、
  // 無指定なら従来と完全に同じカードになる。
  // スペースは任意 —「めいく虹」「めいく 虹」のどちらでも同じ。
  // スペース無しを許すと「めいくで作った」「めいくしたい」のような
  // ふつうの会話にも一致してしまうため、続く文字列が丸ごと装飾として
  // 解釈できた場合(または何も続かない場合)だけコマンドとして扱う。
  const replyMake = text.match(/^めいく[ 　]*(.*)$/s)
  if (
    replyMake &&
    isPureParamString(replyMake[1]) &&
    ctx.isGroup &&
    ctx.groupId &&
    ctx.quotedMessageId
  ) {
    const original = await getGroupMessage(env, ctx.groupId, ctx.quotedMessageId)
    if (!original) {
      return [{ type: 'text', text: '元のメッセージが見つかりませんでした(古すぎるか、記録前の発言かもしれません)' }]
    }
    const params = parseQuoteParams(replyMake[1] ?? null)
    const imageId = await saveQuote(
      env,
      ctx.groupId,
      original.user_id,
      original.display_name ?? '不明',
      original.picture_url,
      original.message_text,
      { params, baseUrl: ctx.baseUrl }
    )
    return [buildQuoteImageMessage(ctx.baseUrl, imageId)]
  }

  // 通常モード: 「めいく:テキスト」「めいく<装飾>:テキスト」。
  // スペースは任意 —「めいく虹:あ」「めいく 虹:あ」のどちらでも同じ。
  // 装飾は最初の「:」までの部分だけを見る(本文に「:」が含まれても、
  //   最初の1個だけを区切りにする)。
  // 装飾部分と区切り文字を別々に捕獲する。区切り文字を捕獲しておくのは、
  // 装飾として解釈できなかったときに元の文字列を正しく復元するため
  // (「めいくで作った:test」の本文は「で作った:test」でなければならない)。
  const quoteMatch = text.match(/^めいく[ 　]*([^:：]*)([:：])\s*(.+)$/s)
  if (quoteMatch && ctx.isGroup && ctx.groupId && ctx.userId) {
    // 「:」の前の文字列が丸ごと装飾として解釈できたときだけ装飾と見なす。
    // 解釈できない文字が混じっている場合は装飾ではなく本文の一部として
    // 扱う(勝手に装飾を当てない)。
    const rawParam = quoteMatch[1] ?? ''
    const sep = quoteMatch[2]
    const isParam = isPureParamString(rawParam)
    const params = parseQuoteParams(isParam ? rawParam : null)
    const quoteText = (isParam ? quoteMatch[3] : `${rawParam}${sep}${quoteMatch[3]}`).trim()
    const imageId = await saveQuote(
      env,
      ctx.groupId,
      ctx.userId,
      ctx.displayName ?? '不明',
      ctx.pictureUrl,
      quoteText,
      { params, baseUrl: ctx.baseUrl }
    )
    return [buildQuoteImageMessage(ctx.baseUrl, imageId)]
  }

  if (text === 'オセロ開始' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const result = await startOthello(env, ctx.groupId, ctx.userId, ctx.displayName)
    if (!result.ok) return [{ type: 'text', text: result.reason }]
    // If starting this game just cleaned up a previous game that had timed
    // out from 5+ minutes of inactivity, mention that before the new board.
    const messages: LineMessage[] = []
    if (result.timeoutMessage) messages.push({ type: 'text', text: result.timeoutMessage })
    messages.push(buildOthelloMessage(result.game))
    return messages
  }

  if (text === 'オセロ参加' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const result = await joinOthello(env, ctx.groupId, ctx.userId, ctx.displayName)
    if (!result.ok) return [{ type: 'text', text: result.reason }]
    return [buildOthelloMessage(result.game)]
  }

  if (text === 'オセロ終了' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const result = await endOthello(env, ctx.groupId, ctx.userId)
    return [{ type: 'text', text: result.ok ? 'オセロを終了しました' : result.reason }]
  }

  if (text === 'オセロ戦績' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const record = await getOthelloRecord(env, ctx.groupId, ctx.userId)
    if (!record) return [{ type: 'text', text: 'まだ対局結果がありません' }]
    return [{ type: 'text', text: `オセロ戦績\n勝ち: ${record.wins}\n負け: ${record.losses}\n引き分け: ${record.draws}` }]
  }

  const tagAddMatch = text.match(/^タグ追加\s*(.+)$/)
  if (tagAddMatch && ctx.isGroup && ctx.groupId) {
    await addTagToGroup(env, ctx.groupId, tagAddMatch[1].trim())
    return [{ type: 'text', text: `タグ「${tagAddMatch[1].trim()}」を追加しました` }]
  }
  const tagRemoveMatch = text.match(/^タグ削除\s*(.+)$/)
  if (tagRemoveMatch && ctx.isGroup && ctx.groupId) {
    await removeTagFromGroup(env, ctx.groupId, tagRemoveMatch[1].trim())
    return [{ type: 'text', text: `タグ「${tagRemoveMatch[1].trim()}」を削除しました` }]
  }
  if (text === 'タグ一覧' && ctx.isGroup && ctx.groupId) {
    const tags = await listGroupTags(env, ctx.groupId)
    return [{ type: 'text', text: tags.length > 0 ? `タグ: ${tags.join('、')}` : 'タグは設定されていません' }]
  }

  if (text === '称号一覧' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const titles = await listUserTitles(env, ctx.userId, ctx.groupId)
    if (titles.length === 0) return [{ type: 'text', text: '所持している称号はありません' }]
    const equipped = await getEquippedTitle(env, ctx.userId, ctx.groupId)
    const lines = titles.map((t) => (t === equipped ? `★${t}（装備中）` : `・${t}`))
    return [{ type: 'text', text: `所持称号一覧\n${lines.join('\n')}` }]
  }

  const equipMatch = text.match(/^称号装備\s*(.+)$/)
  if (equipMatch && ctx.isGroup && ctx.groupId && ctx.userId) {
    const titleName = equipMatch[1].trim()
    const owned = await listUserTitles(env, ctx.userId, ctx.groupId)
    if (!owned.includes(titleName)) {
      return [{ type: 'text', text: `「${titleName}」は所持していません` }]
    }
    await equipTitle(env, ctx.userId, ctx.groupId, titleName)
    return [{ type: 'text', text: `称号「${titleName}」を装備しました` }]
  }

  if (text === '称号確認' && ctx.isGroup && ctx.groupId && ctx.userId) {
    const equipped = await getEquippedTitle(env, ctx.userId, ctx.groupId)
    return [{ type: 'text', text: equipped ? `装備中の称号: ${equipped}` : '称号は装備していません' }]
  }

  return []
}


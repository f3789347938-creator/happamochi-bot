// ─── Quote card image delivery ───
// Public, unauthenticated, plain-HTTPS GET endpoint that LINE's servers
// fetch directly when rendering an imageMessage (originalContentUrl /
// previewImageUrl). Serves the PNG bytes generated by generateQuoteCardPng
// and stored in quote_images.image_data (see features/quote.ts).
app.get('/quote-image/:id', async (c) => {
  const id = c.req.param('id')
  const row = await c.env.DB.prepare(`SELECT image_data FROM quote_images WHERE id = ?`)
    .bind(id)
    .first<{ image_data: ArrayBuffer }>()
  if (!row) return c.notFound()
  // D1's local (workerd/miniflare) emulation sometimes returns a BLOB column
  // as a plain JS Array of byte values instead of an ArrayBuffer. Passing
  // that array straight into `new Response()` gets it silently stringified
  // (BodyInit coercion calls String()/Array.prototype.join on it), which is
  // exactly the "137,80,78,71,..." decimal-CSV corruption bug. Normalize to
  // a real ArrayBuffer regardless of which shape D1 handed back.
  const raw = row.image_data as unknown
  const bytes = Array.isArray(raw) ? Uint8Array.from(raw as number[]) : new Uint8Array(raw as ArrayBuffer)
  return new Response(bytes, {
    headers: {
      'Content-Type': 'image/png',
      'Cache-Control': 'public, max-age=31536000, immutable',
    },
  })
})

